/**
 * 로컬 사전에서 포켓몬 검색
 * @param {string} name
 */
function getFallbackPokemon(name) {
  if (!name) return null;
  const cleaned = name.trim();
  if (POKEMON_FALLBACK_DATA[cleaned]) {
    return {
      found: true,
      recognizedName: cleaned,
      ...POKEMON_FALLBACK_DATA[cleaned]
    };
  }
  return null;
}

